package com.pilotapi.integration.openapi;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.node.IntNode;
import com.fasterxml.jackson.databind.node.MissingNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import com.pilotapi.integration.openapi.ComplianceFinding.Category;
import com.pilotapi.integration.openapi.ComplianceFinding.Severity;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;

import static com.pilotapi.integration.openapi.ComplianceFinding.Category.METADATA;
import static com.pilotapi.integration.openapi.ComplianceFinding.Category.PARAMETERS;
import static com.pilotapi.integration.openapi.ComplianceFinding.Category.PATHS;
import static com.pilotapi.integration.openapi.ComplianceFinding.Category.REQUEST_BODIES;
import static com.pilotapi.integration.openapi.ComplianceFinding.Category.RESPONSES;
import static com.pilotapi.integration.openapi.ComplianceFinding.Category.SCHEMAS;
import static com.pilotapi.integration.openapi.ComplianceFinding.Category.SECURITY;
import static com.pilotapi.integration.openapi.ComplianceFinding.Severity.ERROR;
import static com.pilotapi.integration.openapi.ComplianceFinding.Severity.INFO;
import static com.pilotapi.integration.openapi.ComplianceFinding.Severity.WARN;

/**
 * Compares the shared OpenAPI specification (the contract) against the
 * specification generated by this application and classifies every
 * difference as {@link Severity#ERROR}, {@link Severity#WARN} or
 * {@link Severity#INFO}.
 *
 * <p>Both documents are compared as raw JSON trees so OpenAPI 3.1 constructs
 * (type arrays, {@code "null"} types, {@code oneOf} nullability) survive
 * intact. Schemas are compared structurally by following {@code $ref}s, so a
 * component named differently in each document is still compared.
 */
public class OpenApiComparator {

    private static final List<String> HTTP_METHODS =
        List.of("get", "put", "post", "delete", "options", "head", "patch", "trace");
    private static final String NULL_TYPE = "null";
    private static final String NONE = "<none>";
    private static final int MAX_REF_DEPTH = 32;

    private final JsonNode spec;
    private final JsonNode app;
    private final List<ComplianceFinding> findings = new ArrayList<>();
    private final Set<String> comparedComponentPairs = new HashSet<>();

    public OpenApiComparator(JsonNode spec, JsonNode app) {
        this.spec = spec;
        this.app = app;
    }

    public List<ComplianceFinding> compare() {
        findings.clear();
        comparedComponentPairs.clear();
        compareMetadata();
        compareSecuritySchemes();
        comparePaths();
        return List.copyOf(findings);
    }

    // ---------------------------------------------------------------- metadata

    private void compareMetadata() {
        compareValue(WARN, METADATA, "openapi", "OpenAPI version", spec.path("openapi"), app.path("openapi"));
        for (String field : List.of("title", "summary", "description", "version", "termsOfService")) {
            compareValue(WARN, METADATA, "info." + field, "Info " + field,
                spec.path("info").path(field), app.path("info").path(field));
        }
        for (String field : List.of("name", "url", "email")) {
            compareValue(WARN, METADATA, "info.contact." + field, "Contact " + field,
                spec.path("info").path("contact").path(field), app.path("info").path("contact").path(field));
        }
        for (String field : List.of("name", "identifier", "url")) {
            compareValue(WARN, METADATA, "info.license." + field, "License " + field,
                spec.path("info").path("license").path(field), app.path("info").path("license").path(field));
        }

        Set<String> specServers = textValues(spec.path("servers"), "url");
        Set<String> appServers = textValues(app.path("servers"), "url");
        if (!specServers.equals(appServers)) {
            add(WARN, METADATA, "servers", "Server URLs differ", specServers.toString(), appServers.toString());
        }

        Map<String, JsonNode> specTags = byName(spec.path("tags"));
        Map<String, JsonNode> appTags = byName(app.path("tags"));
        specTags.forEach((name, tag) -> {
            JsonNode appTag = appTags.get(name);
            if (appTag == null) {
                add(WARN, METADATA, "tags." + name, "Tag is not defined by the app", "present", "missing");
            } else {
                compareValue(INFO, METADATA, "tags." + name, "Tag description",
                    tag.path("description"), appTag.path("description"));
            }
        });
        appTags.keySet().stream()
            .filter(name -> !specTags.containsKey(name))
            .forEach(name -> add(WARN, METADATA, "tags." + name,
                "Tag is not defined in the shared spec", "missing", "present"));
    }

    // ---------------------------------------------------------------- security

    private void compareSecuritySchemes() {
        JsonNode specSchemes = spec.path("components").path("securitySchemes");
        JsonNode appSchemes = app.path("components").path("securitySchemes");
        Set<String> matchedAppSchemes = new HashSet<>();

        specSchemes.properties().forEach(entry -> {
            String name = entry.getKey();
            String location = "components.securitySchemes." + name;
            JsonNode specScheme = entry.getValue();
            JsonNode appScheme = appSchemes.get(name);
            if (appScheme != null) {
                matchedAppSchemes.add(name);
                if (!schemeSignature(specScheme).equals(schemeSignature(appScheme))) {
                    add(ERROR, SECURITY, location, "Security scheme definition differs",
                        schemeSignature(specScheme).toString(), schemeSignature(appScheme).toString());
                }
                compareValue(INFO, SECURITY, location, "Security scheme description",
                    specScheme.path("description"), appScheme.path("description"));
                return;
            }
            String equivalent = findEquivalentScheme(specScheme, appSchemes, matchedAppSchemes);
            if (equivalent != null) {
                matchedAppSchemes.add(equivalent);
                add(ERROR, SECURITY, location, "Security scheme is defined by the app under a different name",
                    name, equivalent);
            } else {
                add(ERROR, SECURITY, location, "Security scheme is missing",
                    schemeSignature(specScheme).toString(), NONE);
            }
        });

        appSchemes.properties().stream()
            .filter(entry -> !matchedAppSchemes.contains(entry.getKey()))
            .forEach(entry -> add(ERROR, SECURITY, "components.securitySchemes." + entry.getKey(),
                "Security scheme is not defined in the shared spec", NONE,
                schemeSignature(entry.getValue()).toString()));
    }

    private String findEquivalentScheme(JsonNode specScheme, JsonNode appSchemes, Set<String> alreadyMatched) {
        JsonNode signature = schemeSignature(specScheme);
        return appSchemes.properties().stream()
            .filter(entry -> !alreadyMatched.contains(entry.getKey()))
            .filter(entry -> schemeSignature(entry.getValue()).equals(signature))
            .map(Map.Entry::getKey)
            .findFirst()
            .orElse(null);
    }

    /** A scheme definition stripped of free text, so only behaviour-affecting fields are compared. */
    private static JsonNode schemeSignature(JsonNode scheme) {
        ObjectNode signature = scheme.deepCopy();
        signature.remove("description");
        if (signature.hasNonNull("scheme")) {
            signature.put("scheme", signature.get("scheme").asText().toLowerCase(Locale.ROOT));
        }
        return signature;
    }

    private void compareOperationSecurity(String location, JsonNode specOperation, JsonNode appOperation) {
        JsonNode specSecurity = specOperation.has("security") ? specOperation.get("security") : spec.path("security");
        JsonNode appSecurity = appOperation.has("security") ? appOperation.get("security") : app.path("security");
        // Requirements are compared by the scheme they resolve to, so a renamed scheme is
        // reported once on the scheme itself rather than on every operation.
        if (!requirementSignatures(spec, specSecurity).equals(requirementSignatures(app, appSecurity))) {
            add(ERROR, SECURITY, location, "Security requirements differ",
                requirementNames(specSecurity), requirementNames(appSecurity));
        }
    }

    private static Set<String> requirementSignatures(JsonNode root, JsonNode security) {
        Set<String> signatures = new TreeSet<>();
        for (JsonNode requirement : security) {
            Set<String> parts = new TreeSet<>();
            requirement.properties().forEach(entry -> {
                JsonNode scheme = root.path("components").path("securitySchemes").get(entry.getKey());
                String schemeSignature = scheme == null ? "unknown:" + entry.getKey() : schemeSignature(scheme).toString();
                parts.add(schemeSignature + textValues(entry.getValue(), null));
            });
            signatures.add(parts.toString());
        }
        return signatures;
    }

    private static String requirementNames(JsonNode security) {
        List<String> requirements = new ArrayList<>();
        for (JsonNode requirement : security) {
            requirements.add(new TreeSet<>(names(requirement)).toString());
        }
        return requirements.isEmpty() ? NONE : requirements.toString();
    }

    // ---------------------------------------------------------------- paths and operations

    private void comparePaths() {
        JsonNode specPaths = spec.path("paths");
        JsonNode appPaths = app.path("paths");

        specPaths.properties().forEach(entry -> {
            String path = entry.getKey();
            JsonNode specItem = deref(spec, entry.getValue());
            JsonNode appItem = deref(app, appPaths.path(path));
            for (String method : operationMethods(specItem)) {
                String location = method.toUpperCase(Locale.ROOT) + " " + path;
                if (!appItem.has(method)) {
                    add(ERROR, PATHS, location, "Operation defined in the shared spec is not implemented",
                        "implemented", "missing");
                } else {
                    compareOperation(location, specItem, specItem.get(method), appItem, appItem.get(method));
                }
            }
        });

        appPaths.properties().forEach(entry -> {
            String path = entry.getKey();
            JsonNode specItem = deref(spec, specPaths.path(path));
            for (String method : operationMethods(deref(app, entry.getValue()))) {
                if (!specItem.has(method)) {
                    add(WARN, PATHS, method.toUpperCase(Locale.ROOT) + " " + path,
                        "Operation is implemented but not defined in the shared spec", "missing", "implemented");
                }
            }
        });
    }

    private static List<String> operationMethods(JsonNode pathItem) {
        return HTTP_METHODS.stream().filter(pathItem::has).toList();
    }

    private void compareOperation(String location, JsonNode specItem, JsonNode specOperation,
                                  JsonNode appItem, JsonNode appOperation) {
        for (String field : List.of("tags", "operationId", "deprecated")) {
            compareValue(WARN, METADATA, location, "Operation " + field,
                specOperation.path(field), appOperation.path(field));
        }
        for (String field : List.of("summary", "description")) {
            compareValue(INFO, METADATA, location, "Operation " + field,
                specOperation.path(field), appOperation.path(field));
        }
        compareParameters(location, collectParameters(spec, specItem, specOperation),
            collectParameters(app, appItem, appOperation));
        compareRequestBody(location, deref(spec, specOperation.path("requestBody")),
            deref(app, appOperation.path("requestBody")));
        compareResponses(location, specOperation.path("responses"), appOperation.path("responses"));
        compareOperationSecurity(location, specOperation, appOperation);
    }

    // ---------------------------------------------------------------- parameters

    /** Path-level parameters overlaid by operation-level ones, keyed by location and name. */
    private static Map<String, JsonNode> collectParameters(JsonNode root, JsonNode pathItem, JsonNode operation) {
        Map<String, JsonNode> parameters = new LinkedHashMap<>();
        for (JsonNode source : List.of(pathItem.path("parameters"), operation.path("parameters"))) {
            for (JsonNode raw : source) {
                JsonNode parameter = deref(root, raw);
                String in = parameter.path("in").asText();
                String name = parameter.path("name").asText();
                // Header names are case-insensitive on the wire.
                parameters.put(in + ":" + ("header".equals(in) ? name.toLowerCase(Locale.ROOT) : name), parameter);
            }
        }
        return parameters;
    }

    private void compareParameters(String location, Map<String, JsonNode> specParameters,
                                   Map<String, JsonNode> appParameters) {
        specParameters.forEach((key, specParameter) -> {
            String parameterLocation = location + " > parameter " + describeParameter(specParameter);
            JsonNode appParameter = appParameters.get(key);
            boolean specRequired = specParameter.path("required").asBoolean(false);
            if (appParameter == null) {
                add(specRequired ? ERROR : WARN, PARAMETERS, parameterLocation,
                    specRequired ? "Required parameter is missing" : "Optional parameter is missing",
                    "present", "missing");
                return;
            }
            boolean appRequired = appParameter.path("required").asBoolean(false);
            if (specRequired != appRequired) {
                add(ERROR, PARAMETERS, parameterLocation, "Parameter required flag differs",
                    String.valueOf(specRequired), String.valueOf(appRequired));
            }
            compareValue(INFO, PARAMETERS, parameterLocation, "Parameter description",
                specParameter.path("description"), appParameter.path("description"));
            compareSchema(parameterLocation + " schema", specParameter.path("schema"), appParameter.path("schema"));
        });

        appParameters.forEach((key, appParameter) -> {
            if (!specParameters.containsKey(key)) {
                add(WARN, PARAMETERS, location + " > parameter " + describeParameter(appParameter),
                    "Parameter is not defined in the shared spec", "missing", "present");
            }
        });
    }

    private static String describeParameter(JsonNode parameter) {
        return parameter.path("in").asText() + ":" + parameter.path("name").asText();
    }

    // ---------------------------------------------------------------- request bodies and responses

    private void compareRequestBody(String location, JsonNode specBody, JsonNode appBody) {
        String bodyLocation = location + " > requestBody";
        if (specBody.isMissingNode() && appBody.isMissingNode()) {
            return;
        }
        if (specBody.isMissingNode()) {
            add(WARN, REQUEST_BODIES, bodyLocation, "Request body is not defined in the shared spec",
                "missing", "present");
            return;
        }
        if (appBody.isMissingNode()) {
            add(ERROR, REQUEST_BODIES, bodyLocation, "Request body is missing", "present", "missing");
            return;
        }
        boolean specRequired = specBody.path("required").asBoolean(false);
        boolean appRequired = appBody.path("required").asBoolean(false);
        if (specRequired != appRequired) {
            add(ERROR, REQUEST_BODIES, bodyLocation, "Request body required flag differs",
                String.valueOf(specRequired), String.valueOf(appRequired));
        }
        compareValue(INFO, REQUEST_BODIES, bodyLocation, "Request body description",
            specBody.path("description"), appBody.path("description"));
        compareContent(REQUEST_BODIES, bodyLocation, specBody.path("content"), appBody.path("content"));
    }

    private void compareResponses(String location, JsonNode specResponses, JsonNode appResponses) {
        specResponses.properties().forEach(entry -> {
            String status = entry.getKey();
            String responseLocation = location + " > response " + status;
            JsonNode specResponse = deref(spec, entry.getValue());
            JsonNode appResponse = deref(app, appResponses.path(status));
            if (appResponse.isMissingNode()) {
                boolean success = status.startsWith("2");
                add(success ? ERROR : WARN, RESPONSES, responseLocation,
                    success ? "Success response is missing" : "Error response is missing", "present", "missing");
                return;
            }
            compareValue(INFO, RESPONSES, responseLocation, "Response description",
                specResponse.path("description"), appResponse.path("description"));
            compareContent(RESPONSES, responseLocation, specResponse.path("content"), appResponse.path("content"));
        });

        names(appResponses).stream()
            .filter(status -> !specResponses.has(status))
            .forEach(status -> add(WARN, RESPONSES, location + " > response " + status,
                "Response is not defined in the shared spec", "missing", "present"));
    }

    private void compareContent(Category category, String location, JsonNode specContent, JsonNode appContent) {
        Set<String> specMediaTypes = new TreeSet<>(names(specContent));
        Set<String> appMediaTypes = new TreeSet<>(names(appContent));
        if (!specMediaTypes.equals(appMediaTypes)) {
            add(ERROR, category, location, "Media types differ", specMediaTypes.toString(), appMediaTypes.toString());
        }

        for (String mediaType : specMediaTypes) {
            JsonNode specSchema = specContent.get(mediaType).get("schema");
            if (specSchema == null) {
                continue;
            }
            String schemaLocation = location + " [" + mediaType + "] schema";
            JsonNode appMedia = appContent.get(mediaType);
            if (appMedia == null && appMediaTypes.size() == 1) {
                // e.g. application/json in the spec versus */* from springdoc: still compare the payload.
                appMedia = appContent.get(appMediaTypes.iterator().next());
            }
            if (appMedia == null) {
                if (appMediaTypes.isEmpty()) {
                    add(ERROR, SCHEMAS, schemaLocation, "Schema is missing", "present", "missing");
                }
                continue;
            }
            JsonNode appSchema = appMedia.get("schema");
            if (appSchema == null) {
                add(ERROR, SCHEMAS, schemaLocation, "Schema is missing", "present", "missing");
                continue;
            }
            compareSchema(schemaLocation, specSchema, appSchema);
        }
    }

    // ---------------------------------------------------------------- schemas

    private record NormalizedSchema(JsonNode node, String refName, boolean nullable, Set<String> types) {
    }

    private void compareSchema(String location, JsonNode specRaw, JsonNode appRaw) {
        if (specRaw.isMissingNode()) {
            return;
        }
        if (appRaw.isMissingNode()) {
            add(ERROR, SCHEMAS, location, "Schema is missing", "present", "missing");
            return;
        }
        NormalizedSchema specSchema = normalize(spec, specRaw);
        NormalizedSchema appSchema = normalize(app, appRaw);

        // Nullability belongs to the use site (e.g. oneOf [null, $ref]), so check it before de-duplicating.
        if (specSchema.nullable() != appSchema.nullable()) {
            add(ERROR, SCHEMAS, location, "Nullability differs",
                nullability(specSchema.nullable()), nullability(appSchema.nullable()));
        }

        String schemaLocation = location;
        if (specSchema.refName() != null && appSchema.refName() != null) {
            // Each pair of components is compared once; this also stops recursive schemas from looping.
            if (!comparedComponentPairs.add(specSchema.refName() + "->" + appSchema.refName())) {
                return;
            }
            schemaLocation = "components.schemas." + specSchema.refName();
            if (!specSchema.refName().equals(appSchema.refName())) {
                add(INFO, SCHEMAS, location, "Referenced component schema name differs",
                    specSchema.refName(), appSchema.refName());
                schemaLocation += " (app: " + appSchema.refName() + ")";
            }
        }

        if (!compareTypes(schemaLocation, specSchema, appSchema)) {
            return;
        }

        JsonNode specNode = specSchema.node();
        JsonNode appNode = appSchema.node();
        compareValue(ERROR, SCHEMAS, schemaLocation, "Format", specNode.path("format"), appNode.path("format"));
        Set<String> specEnum = textValues(specNode.path("enum"), null);
        Set<String> appEnum = textValues(appNode.path("enum"), null);
        if (!specEnum.equals(appEnum)) {
            add(ERROR, SCHEMAS, schemaLocation, "Enum values differ", specEnum.toString(), appEnum.toString());
        }
        for (String field : List.of("pattern", "default")) {
            compareValue(ERROR, SCHEMAS, schemaLocation, "Schema " + field, specNode.path(field), appNode.path(field));
        }
        for (String field : List.of("minLength", "maxLength", "minimum", "maximum",
            "exclusiveMinimum", "exclusiveMaximum", "minItems", "maxItems")) {
            compareNumber(ERROR, SCHEMAS, schemaLocation, "Schema " + field,
                withZeroDefault(field, specNode.path(field)), withZeroDefault(field, appNode.path(field)));
        }
        for (String field : List.of("example", "examples", "description")) {
            compareValue(INFO, SCHEMAS, schemaLocation, "Schema " + field, specNode.path(field), appNode.path(field));
        }
        for (String keyword : List.of("oneOf", "anyOf", "allOf")) {
            JsonNode specBranches = specNode.path(keyword);
            JsonNode appBranches = appNode.path(keyword);
            if (specBranches.size() != appBranches.size()) {
                add(ERROR, SCHEMAS, schemaLocation, "Composition (" + keyword + ") differs",
                    specBranches.size() + " branch(es)", appBranches.size() + " branch(es)");
            }
            int sharedBranches = Math.min(specBranches.size(), appBranches.size());
            for (int index = 0; index < sharedBranches; index++) {
                compareSchema(schemaLocation + "." + keyword + "[" + index + "]",
                    specBranches.get(index), appBranches.get(index));
            }
        }

        compareProperties(schemaLocation, specNode, appNode);
        if (specNode.has("items")) {
            compareSchema(schemaLocation + "[]", specNode.path("items"), appNode.path("items"));
        }
        if (specNode.path("additionalProperties").isObject() && appNode.path("additionalProperties").isObject()) {
            compareSchema(schemaLocation + "{*}", specNode.path("additionalProperties"),
                appNode.path("additionalProperties"));
        }
    }

    /** @return {@code false} when the types are incompatible and deeper comparison is pointless. */
    private boolean compareTypes(String location, NormalizedSchema specSchema, NormalizedSchema appSchema) {
        Set<String> specTypes = specSchema.types();
        Set<String> appTypes = appSchema.types();
        if (specTypes.equals(appTypes)) {
            return true;
        }
        if (specTypes.isEmpty() || appTypes.isEmpty()) {
            // A missing type on either side is a base-type mismatch (e.g. string vs an untyped schema).
            add(ERROR, SCHEMAS, location, "Type is unconstrained in one document",
                typesText(specTypes), typesText(appTypes));
            return !appTypes.isEmpty();
        }
        Set<String> overlap = new TreeSet<>(specTypes);
        overlap.retainAll(appTypes);
        if (!overlap.isEmpty()) {
            add(INFO, SCHEMAS, location, "Alternate types differ", typesText(specTypes), typesText(appTypes));
            return true;
        }
        if (isNumeric(specTypes) && isNumeric(appTypes)) {
            add(ERROR, SCHEMAS, location, "Numeric type differs", typesText(specTypes), typesText(appTypes));
            return true;
        }
        add(ERROR, SCHEMAS, location, "Base type is incompatible", typesText(specTypes), typesText(appTypes));
        return false;
    }

    private void compareProperties(String location, JsonNode specNode, JsonNode appNode) {
        JsonNode specProperties = specNode.path("properties");
        JsonNode appProperties = appNode.path("properties");
        specProperties.properties().forEach(entry -> {
            String propertyLocation = location + "." + entry.getKey();
            if (!appProperties.has(entry.getKey())) {
                add(ERROR, SCHEMAS, propertyLocation, "Property is missing", "present", "missing");
            } else {
                compareSchema(propertyLocation, entry.getValue(), appProperties.get(entry.getKey()));
            }
        });
        names(appProperties).stream()
            .filter(name -> !specProperties.has(name))
            .forEach(name -> add(WARN, SCHEMAS, location + "." + name,
                "Property is not defined in the shared spec", "missing", "present"));

        Set<String> specRequired = textValues(specNode.path("required"), null);
        Set<String> appRequired = textValues(appNode.path("required"), null);
        specRequired.stream()
            .filter(name -> !appRequired.contains(name))
            .forEach(name -> add(ERROR, SCHEMAS, location + "." + name,
                "Property is required in the shared spec but optional in the app", "required", "optional"));
        appRequired.stream()
            .filter(name -> !specRequired.contains(name))
            .forEach(name -> add(ERROR, SCHEMAS, location + "." + name,
                "Property is optional in the shared spec but required in the app", "optional", "required"));
    }

    /**
     * Follows {@code $ref}s and unwraps single-branch compositions such as
     * {@code oneOf: [{type: "null"}, {$ref: ...}]}, recording nullability and
     * the referenced component name along the way.
     */
    private static NormalizedSchema normalize(JsonNode root, JsonNode raw) {
        JsonNode node = raw;
        String refName = null;
        boolean nullable = false;
        for (int depth = 0; depth < MAX_REF_DEPTH; depth++) {
            if (node.has("$ref")) {
                String ref = node.get("$ref").asText();
                refName = ref.substring(ref.lastIndexOf('/') + 1);
                node = deref(root, node);
                continue;
            }
            JsonNode singleBranch = null;
            for (String keyword : List.of("oneOf", "anyOf", "allOf")) {
                if (!node.has(keyword)) {
                    continue;
                }
                List<JsonNode> branches = new ArrayList<>();
                for (JsonNode branch : node.get(keyword)) {
                    if (NULL_TYPE.equals(branch.path("type").asText(null))) {
                        nullable = true;
                    } else {
                        branches.add(branch);
                    }
                }
                if (branches.size() == 1 && node.get(keyword).size() <= 2) {
                    singleBranch = branches.get(0);
                }
            }
            if (singleBranch == null) {
                break;
            }
            node = singleBranch;
        }

        Set<String> types = new TreeSet<>();
        JsonNode type = node.path("type");
        if (type.isArray()) {
            type.forEach(value -> types.add(value.asText()));
        } else if (type.isTextual()) {
            types.add(type.asText());
        }
        if (types.remove(NULL_TYPE) || node.path("nullable").asBoolean(false)) {
            nullable = true;
        }
        if (types.isEmpty() && node.has("properties")) {
            types.add("object");
        } else if (types.isEmpty() && node.has("items")) {
            types.add("array");
        }
        return new NormalizedSchema(node, refName, nullable, types);
    }

    private static boolean isNumeric(Set<String> types) {
        return types.stream().allMatch(type -> "integer".equals(type) || "number".equals(type));
    }

    private static String typesText(Set<String> types) {
        return types.isEmpty() ? NONE : types.toString();
    }

    private static String nullability(boolean nullable) {
        return nullable ? "nullable" : "non-nullable";
    }

    // ---------------------------------------------------------------- helpers

    private static JsonNode deref(JsonNode root, JsonNode node) {
        JsonNode current = node;
        for (int depth = 0; depth < MAX_REF_DEPTH && current.has("$ref"); depth++) {
            String ref = current.get("$ref").asText();
            current = ref.startsWith("#") ? root.at(ref.substring(1)) : MissingNode.getInstance();
        }
        return current;
    }

    private static Set<String> textValues(JsonNode array, String field) {
        Set<String> values = new LinkedHashSet<>();
        for (JsonNode element : array) {
            JsonNode value = field == null ? element : element.path(field);
            if (!value.isNull() && !value.isMissingNode()) {
                values.add(value.asText());
            }
        }
        return new TreeSet<>(values);
    }

    private static List<String> names(JsonNode object) {
        List<String> names = new ArrayList<>();
        object.fieldNames().forEachRemaining(names::add);
        return names;
    }

    private static Map<String, JsonNode> byName(JsonNode array) {
        Map<String, JsonNode> values = new LinkedHashMap<>();
        array.forEach(element -> values.put(element.path("name").asText(), element));
        return values;
    }

    private void compareValue(Severity severity, Category category, String location, String what,
                              JsonNode expected, JsonNode actual) {
        String expectedText = display(expected);
        String actualText = display(actual);
        if (!expectedText.equals(actualText)) {
            add(severity, category, location, what + " differs", expectedText, actualText);
        }
    }

    /** JSON Schema treats an absent {@code minLength}/{@code minItems} as 0, so both spellings compare equal. */
    private static JsonNode withZeroDefault(String field, JsonNode value) {
        return value.isMissingNode() && ("minLength".equals(field) || "minItems".equals(field))
            ? IntNode.valueOf(0)
            : value;
    }

    /** Compares numeric keywords by value, so {@code 1} and {@code 1.0} are treated as equal. */
    private void compareNumber(Severity severity, Category category, String location, String what,
                               JsonNode expected, JsonNode actual) {
        if (expected.isNumber() && actual.isNumber()
            && expected.decimalValue().compareTo(actual.decimalValue()) == 0) {
            return;
        }
        compareValue(severity, category, location, what, expected, actual);
    }

    private static String display(JsonNode node) {
        if (node == null || node.isMissingNode()) {
            return NONE;
        }
        return node.isValueNode() ? node.asText() : node.toString();
    }

    private void add(Severity severity, Category category, String location, String message,
                     String expected, String actual) {
        findings.add(new ComplianceFinding(severity, category, location, message, expected, actual));
    }
}
